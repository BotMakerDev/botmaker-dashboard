package com.botmaker.dashboard.github;

import com.fasterxml.jackson.databind.JsonNode;
import com.fasterxml.jackson.databind.ObjectMapper;
import org.junit.jupiter.api.Test;

import java.util.List;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertFalse;
import static org.junit.jupiter.api.Assertions.assertTrue;

class SubmissionTest {

    private static final ObjectMapper MAPPER = new ObjectMapper();

    private static Submission with(String... files) {
        return new Submission(Queue.REPO, 12, "add an entry", "someone", "abc123",
                "https://github.com/x", List.of(files), Checks.unknown(), false);
    }

    private static JsonNode json(String text) {
        try {
            return MAPPER.readTree(text);
        } catch (Exception e) {
            throw new AssertionError(e);
        }
    }

    @Test
    void aBotEntryIsOneCatalogFile() {
        Submission bot = with("bots/somedev__firestone.json");
        assertTrue(bot.wellShaped());
        assertEquals("somedev/firestone", bot.claimedKey().orElseThrow());
        assertEquals("bot somedev/firestone", bot.shape());
    }

    @Test
    void aPluginEntryIsOneCatalogFile() {
        Submission plugin = with("plugins/com.example.demo.json");
        assertTrue(plugin.wellShaped());
        assertEquals("com.example.demo", plugin.claimedKey().orElseThrow());
        assertEquals("plugin com.example.demo", plugin.shape());
    }

    @Test
    void anAdminsRankChangeIsOneCatalogFileNamingNoEntry() {
        Submission ranks = with("publishers.json");
        assertTrue(ranks.wellShaped());
        assertTrue(ranks.claimedKey().isEmpty());
        assertEquals("ranks (publishers.json)", ranks.shape());
    }

    @Test
    void aPullRequestTouchingAnythingBesidesItsFileIsFlagged() {
        // catalog.json is generated by index.yml; a pull request editing it is held by the merge job.
        Submission sneaky = with("plugins/com.example.demo.json", "catalog.json");
        assertFalse(sneaky.wellShaped());
        assertEquals(List.of("catalog.json"), sneaky.strays());
        assertTrue(sneaky.shape().contains("it should not"));

        Submission ranksAndEntry = with("publishers.json", "bots/somedev__firestone.json");
        assertTrue(ranksAndEntry.entryFile().isEmpty(), "two catalog files are no single one");
        assertTrue(ranksAndEntry.shape().startsWith("no single catalog file"));
    }

    @Test
    void pathsTheCatalogDoesNotTakeAreNoEntry() {
        assertTrue(with("plugins/nested/thing.json").entryFile().isEmpty());
        assertTrue(with("bots/no-separator.json").entryFile().isEmpty(), "a bot's file is owner__repo");
        assertTrue(with(".github/workflows/validate.yml").entryFile().isEmpty());
    }

    @Test
    void aPullRequestIsReadWithItsWaitingLabel() {
        JsonNode pr = json("""
                {"number": 7, "title": "list somedev/firestone", "user": {"login": "octocat"},
                 "head": {"sha": "deadbeef"}, "html_url": "https://github.com/x/y/pull/7",
                 "labels": [{"name": "bug"}, {"name": "waiting"}]}
                """);
        JsonNode files = json("""
                [{"filename": "bots/octocat__firestone.json", "status": "added"}]
                """);
        Submission read = Submission.read(Queue.REPO, pr, Submission.filenames(files), Checks.unknown());
        assertEquals(7, read.number());
        assertEquals("octocat", read.author());
        assertEquals("deadbeef", read.headSha());
        assertEquals("botmaker-catalog#7", read.label());
        assertTrue(read.waiting());

        assertFalse(Submission.read(Queue.REPO, json("{\"number\": 8}"), List.of(), Checks.unknown()).waiting());
    }
}
